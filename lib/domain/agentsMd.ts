export const START = "<!-- aftershock:lessons:start — generated by Aftershock, edits inside are replaced on the next sync -->";
export const END = "<!-- aftershock:lessons:end -->";

/**
 * Writes the lessons into AGENTS.md between markers, one heading level down. Everything outside the
 * markers belongs to the team and is kept as is; running it twice gives the same file.
 */
export function mergeLessons(existing: string | null, lessonsMd: string): string {
  const section = `${START}\n${lessonsMd.trim().replace(/^(#+) /gm, "#$1 ")}\n${END}`;
  if (!existing?.trim()) return `# AGENTS.md\n\n${section}\n`;
  const s = existing.indexOf(START.slice(0, 32));
  const e = existing.indexOf(END);
  if (s >= 0 && e > s) return existing.slice(0, s) + section + existing.slice(e + END.length);
  return `${existing.trimEnd()}\n\n${section}\n`;
}
